#!/usr/bin/env python3
"""
Generate sql_scripts/init_schema.sql (the Postgres first-boot schema) from the
ORM models in libs/duk_common/models.py, so a fresh database always matches the
code instead of an old production dump.

    python3 scripts/generate_init_schema.py > sql_scripts/init_schema.sql

Special cases the ORM can't express:
  * gps_logs is RANGE-partitioned by created_at (partition_manager.py adds the
    monthly children and the DEFAULT partition at startup).
  * The database is stamped at the current Alembic head, so later
    `alembic upgrade head` runs only migrations added after this file.
"""
import os
import sys

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from libs.duk_common.models import Base  # noqa: E402

ALEMBIC_HEAD = "j0e41822mn8k"

GPS_LOGS_DDL = """CREATE TABLE gps_logs (
\tid BIGSERIAL NOT NULL,
\tlat FLOAT,
\tlon FLOAT,
\tspeed FLOAT,
\tevent VARCHAR(30),
\tist_time TIMESTAMP WITHOUT TIME ZONE,
\tcreated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
\ttrip_id INTEGER,
\tgps_time TIMESTAMP WITH TIME ZONE,
\tsource VARCHAR(20),
\tPRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);

CREATE TABLE gps_logs_default PARTITION OF gps_logs DEFAULT;

CREATE INDEX ix_gps_logs_source ON gps_logs (source);
CREATE INDEX ix_gps_logs_created_at ON gps_logs (created_at);
CREATE INDEX ix_gps_logs_trip_id ON gps_logs (trip_id);
"""


def main() -> None:
    dialect = postgresql.dialect()
    out = [
        "-- GENERATED by scripts/generate_init_schema.py from libs/duk_common/models.py.",
        "-- Do not edit by hand; change the models (and add an Alembic migration), then regenerate.",
        "-- Mounted as the Postgres first-boot init script by the root docker-compose.yml.",
        "",
        "BEGIN;",
        "",
    ]
    for table in Base.metadata.sorted_tables:
        if table.name == "gps_logs":
            out.append(GPS_LOGS_DDL)
            continue
        out.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";\n")
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            out.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
        out.append("")

    out += [
        "-- Default route: the dashboard and services use route_id=1.",
        "INSERT INTO routes (id, name) VALUES (1, 'Main route');",
        "SELECT setval(pg_get_serial_sequence('routes', 'id'), 1);",
        "",
        "-- Schema above is already at the latest migration.",
        "CREATE TABLE alembic_version (",
        "\tversion_num VARCHAR(32) NOT NULL,",
        "\tCONSTRAINT alembic_version_pkc PRIMARY KEY (version_num)",
        ");",
        f"INSERT INTO alembic_version (version_num) VALUES ('{ALEMBIC_HEAD}');",
        "",
        "COMMIT;",
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
